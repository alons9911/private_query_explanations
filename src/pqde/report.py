"""Collect the outputs of E1-E5 into ``results/REPORT.md``."""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from .experiments.common import RESULTS_DIR, to_markdown


def _read(path: Path) -> pd.DataFrame | None:
    return pd.read_csv(path) if path.exists() else None


def _fmt(x, nd=3):
    if isinstance(x, float):
        return f"{x:.{nd}f}"
    return str(x)


def _pair_section(pid: str, rep: dict, base: Path) -> list[str]:
    p = rep["pair"]
    prm = rep["parameters"]
    vs = rep["view_stage"]
    syn = " **(synthetic data)**" if p.get("synthetic_data") else ""
    L = [f"### {pid} — {p['dataset']}{syn}", ""]
    L.append(f"* Q1 = `{p['Q1']}` (|Q1| = {p['|Q1|']:,})")
    L.append(f"* Q2 = `{p['Q2']}` (|Q2| = {p['|Q2|']:,}; overlap {p['|Q1 & Q2|']:,})")
    for k, v in p.items():
        if k.startswith("constraint:"):
            paper = p.get("paper_reported", {})
            pp = f" — paper: {paper.get('share_q1')} → {paper.get('share_q2')}" if paper.get("share_q1") is not None else ""
            L.append(f"* {k}: {v['share_Q1']:.1%} → {v['share_Q2']:.1%}{pp}")
    if "refinement_search" in p:
        r = p["refinement_search"]
        L.append(f"* Q' found by the refinement search (predicate distance {r['predicate_distance']:.3f}, "
                 f"{r['n_evaluated']} refinements evaluated)")
    if "selection_rule" in p:
        s = p["selection_rule"]
        L.append(f"* selection rule: `{s['attr']} = '{s['value']}'`, |Q| = {s['size']}, Q_Sigma drops "
                 f"{s['drop_fraction']:.0%}, most uneven over `{s['most_uneven_attr']}` (TVD {s['unevenness_tvd']:.2f})")
    if "conflicts" in p:
        c = p["conflicts"]
        L.append(f"* conflict hypergraph: {c['tuples_in_conflict']} of {p['N']} tuples on {c['edges']} edges")
    L.append(f"* |P| = {prm['|P|']:,}, tau = {prm['tau']}, gamma = {prm['gamma']:.1f}, "
             f"Laplace scale per bin = {prm['laplace_scale_per_bin']:.1f} (sd of released difference "
             f"{prm['sigma_of_released_difference']:.1f})")
    L.append(f"* view stage: overlap of the retained views with the exact top-tau = "
             f"{vs['overlap_with_exact_top_tau']:.2f}")
    qv = vs.get("query_attribute_views", [])
    if qv:
        L.append("* single-atom views on the query attributes (exact rank by Use / coverage / Rep): " + "; ".join(
            f"`{x['view']}` #{x['rank']} ({x['coverage']:.3f} / {x['representativeness']:.2f})" for x in qv[:6]))
    L.append("")
    L.append("| round | view | attribute | bins clearing 2σ | exact |Q1| / |Q2| in view |")
    L.append("|---|---|---|---|---|")
    for e in rep["explanations"]:
        L.append(f"| {e['round']} | `{e['view']}` | {e['attr']} | {', '.join(e['bins_clearing_2sigma']) or '—'} | "
                 f"{e['exact_total_q1']:,} / {e['exact_total_q2']:,} |")
    fig = base / "e1" / pid / "explanations.png"
    if fig.exists():
        L += ["", f"![{pid} released explanations](e1/{pid}/explanations.png)"]
    L.append("")
    return L


def build_report(base: Path | None = None) -> Path:
    base = Path(base or RESULTS_DIR)
    L = ["# Results: Private Query Difference Explanations — reproduction", ""]
    L.append("Generated by `pqde all` (see README). All released quantities are differentially private; fields "
             "named `exact_*` in the JSON files are non-private diagnostics used only to check statements.")
    L.append("")
    e1 = _read(base / "e1" / "summary.csv")
    if e1 is not None:
        L += ["## Table 2 — the twelve query pairs", ""]
        L.append(to_markdown(e1[["pair", "dataset", "synthetic", "Q1", "Q2", "|Q1|", "|Q2|", "|P|", "tau", "gamma"]],
                             floatfmt="{:.1f}"))
        L += ["## E1 — case studies (ε = 1, k = 5, one run per pair)", ""]
        for pid in e1.pair:
            path = base / "e1" / pid / "report.json"
            if path.exists():
                L += _pair_section(pid, json.loads(path.read_text()), base)
    t3 = base / "e2" / "table3_approx_ratio.md"
    if t3.exists():
        meta = json.loads((base / "e2" / "metadata.json").read_text())
        L += ["## E2 — ApproxRatio against B1–B3 (Table 3, Figure 6)", "",
              f"Mean over {meta.get('trials')} trials; metric F_λ with γ_eval = 0.", "", t3.read_text(), ""]
        b = meta.get("baselines", {})
        L.append("B2 (exhaustive) equals B3 (greedy) on every pair, as Proposition 7.1 predicts: "
                 + ", ".join(f"{k}: {'yes' if v['B2_equals_B3'] else 'NO'}" for k, v in b.items()))
        L += ["", "![Figure 6](e2/fig6_approx_ratio.png)", "", "![all pairs](e2/approx_ratio_all_pairs.png)", ""]
    m = _read(base / "e3" / "margins.csv")
    if m is not None:
        L += ["## E3 — what drives accuracy", "", "**Margins** (round-1 candidates of the exact top-τ views):", ""]
        L.append(to_markdown(m[["pair", "gamma", "smoothed_margin_abs", "smoothed_margin_rel", "unsmoothed_margin_rel",
                                "em_resolution", "margin_over_resolution", "use_gap_over_scale"]], floatfmt="{:.4g}"))
        bs = _read(base / "e3" / "bin_stats.csv")
        if bs is not None:
            L += ["**Bins vs γ:**", "", to_markdown(bs, floatfmt="{:.3g}")]
        vs = _read(base / "e3" / "view_stage.csv")
        if vs is not None:
            L += ["**View stage alone** (overlap of retained views with the exact top-τ, vs ε_P):", "",
                  to_markdown(vs.pivot(index="eps_P", columns="pair", values="overlap_mean").reset_index(),
                              floatfmt="{:.3f}"),
                  "![view stage](e3/view_stage_overlap.png)", ""]
        g = _read(base / "e3" / "gamma_sweep.csv")
        if g is not None:
            gm = g[g.setting == "multiplier"].pivot(index="value", columns="pair", values="ratio_B2_mean").reset_index()
            gm = gm.rename(columns={"value": "γ / γ_Eq.12"})
            L += ["**Smoothing γ** (ApproxRatio vs B2, ε = 1):", "", to_markdown(gm, floatfmt="{:.3f}"),
                  "![gamma](e3/gamma_multiplier.png)", ""]
        s = _read(base / "e3" / "budget_split.csv")
        if s is not None:
            L += ["**Budget split** (ε_P/ε_S/ε_H, ApproxRatio vs B2, ε = 1):", "",
                  to_markdown(s.pivot(index="split", columns="pair", values="ratio_B2_mean").reset_index(),
                              floatfmt="{:.3f}")]
    if (base / "e4").exists():
        L += ["## E4 — running time (Figure 7)", "", "![Figure 7](e4/fig7_scalability.png)", ""]
        for name in ("k", "N", "P"):
            df = _read(base / "e4" / f"time_vs_{name}.csv")
            if df is not None:
                L += [f"time vs {name}:", "", to_markdown(df, floatfmt="{:.4g}")]
        tax = _read(base / "e4" / "time_vs_N_tax.csv")
        if tax is not None:
            L += ["time vs N on tax (rows re-sampled from the 200k benchmark file):", "", to_markdown(tax, floatfmt="{:.4g}")]
    rp = _read(base / "e5" / "runtime_per_pair.csv")
    if rp is not None:
        L += ["## E5 — cost of privacy in running time (Figure 8)", "", to_markdown(rp, floatfmt="{:.4g}"),
              "![Figure 8](e5/fig8_runtime.png)", ""]
        g = _read(base / "e5" / "b2_growth.csv")
        if g is not None:
            L += ["B2 growth with the candidate pool:", "", to_markdown(g, floatfmt="{:.4g}")]
    out = base / "REPORT.md"
    out.write_text("\n".join(L) + "\n")
    return out
