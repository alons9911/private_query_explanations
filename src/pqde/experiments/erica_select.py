"""Pick, for each of Erica's ACSIncome (query, constraint) combinations, the minimal
refinement that best shows what the paper is about.

Every validated refinement Erica returned is scored like the case-study search
(:mod:`pqde.search`):

* hidden drift   max TVD between Q(D) and Q'(D) over the explanation attributes
                 that neither query nor any constraint mentions (nor a proxy);
* group drift    the same inside the first constraint's group;
* income         |AVG_{Q'}(PINCP) - re-weighted AVG_Q(PINCP)| / sd(PINCP), only when
                 no predicate mentions income;
* DP visibility  share of eps = 1 released explanations (8 runs) that land on a
                 hidden attribute with a bin clearing twice the noise s.d.

score = (hidden drift + 0.5 group drift + income term) x DP visibility; the
refinement with the highest score is chosen.  Writes
``results/erica_selection/candidates.csv`` and appends the chosen pairs to
``configs/pairs.yaml`` (block marked "generated by pqde run erica").
"""

from __future__ import annotations

import numpy as np
import pandas as pd

from ..benchmarks.erica import decode_all
from ..data import CONFIG_DIR, load_dataset
from ..query import parse
from ..refinement import Constraint
from ..search import dp_check, max_tvd
from .common import out_dir, write_csv, write_json

PROXIES = {"MAR": ["RELP"], "RELP": ["MAR"], "age_bucket": ["AGEP"], "PINCP_bucket": ["PINCP"], "AGEP": ["age_bucket"]}
MARK = "# --- Erica ACSIncome pairs: generated by `pqde run erica` ---"


def _hidden(ds, sqls: list[str], constraints: list[Constraint]) -> list[str]:
    used = set()
    for s in sqls:
        used |= parse(s).attributes()
    for c in constraints:
        used |= parse(c.where).attributes() if c.where else {c.attr}
    for a in list(used):
        used |= set(PROXIES.get(a, []))
    return [a for a in ds.explain_attrs if a not in used]


def score(ds, q1_sql: str, q2_sql: str, constraints: list[Constraint], trials: int, seed: int) -> dict:
    df = ds.raw
    q1, q2 = parse(q1_sql).evaluate(df), parse(q2_sql).evaluate(df)
    hidden = _hidden(ds, [q1_sql, q2_sql], constraints)
    drift, drift_attr = max_tvd(ds, hidden, q1, q2)
    g = constraints[0].group_mask(df)
    gdrift, gattr = max_tvd(ds, hidden, q1 & g, q2 & g)
    income = 0.0
    if "PINCP_bucket" not in parse(q1_sql).attributes() | parse(q2_sql).attributes():
        y = df["PINCP"].to_numpy(dtype=float)
        s2 = (g & q2).sum() / max(q2.sum(), 1)
        cf = s2 * y[q1 & g].mean() + (1 - s2) * y[q1 & ~g].mean() if (q1 & g).any() and (q1 & ~g).any() else np.nan
        income = float(min(abs(y[q2].mean() - cf) / y.std(), 1.0)) if cf == cf else 0.0
    out = {"|Q1|": int(q1.sum()), "|Q2|": int(q2.sum()), "hidden_drift": drift, "hidden_drift_attr": drift_attr,
           "group_drift": gdrift, "group_drift_attr": gattr, "income_term": income,
           "output_jaccard": 1 - (q1 & q2).sum() / max((q1 | q2).sum(), 1)}
    if q2.sum() >= 1000:
        out.update(dp_check(ds, q1, q2, hidden, trials=trials, seed=seed))
    else:
        out.update({"dp_ratio_B2": np.nan, "dp_hidden_rate": 0.0})
    out["score"] = (drift + 0.5 * gdrift + income) * out["dp_hidden_rate"]
    return out


def _yaml_block(chosen: list[dict]) -> str:
    lines = ["", MARK,
             "# Erica's ACSIncome benchmark (Li et al., PVLDB 17(2), 2023): queries and constraints of its",
             "# Figures 2-3; Q' = one of the minimal refinements Erica returned (stored by the authors),",
             "# chosen by `pqde run erica` (results/erica_selection/candidates.csv).", ""]
    for c in chosen:
        lines += [f"ACS_{c['id']}:", "  dataset: acsincome", "  kind: refinement", "  aggregate: PINCP",
                  f"  source: Erica (Li et al., PVLDB 2023), Q{c['query']}^A with {c['constraint_set']}^A; Q' chosen by story score",
                  f"  q1: \"{c['q1_sql']}\"", f"  q2: \"{c['q2_sql']}\"", "  constraints:"]
        for d in c["constraints"]:
            lines.append("    - {" + ", ".join(f"{k}: \"{v}\"" if k == "where" else f"{k}: {v}" for k, v in d.items()) + "}")
        lines.append("")
    return "\n".join(lines) + "\n"


def run(cfg: dict, pairs=None, base=None, quick: bool = False, trials: int | None = None) -> dict:
    ds = load_dataset("acsincome")
    seed = int(cfg["defaults"]["seed"])
    trials = trials or (2 if quick else 8)
    rows, chosen = [], []
    for combo in decode_all(ds.raw):
        if not (combo["all_valid"] and combo["original_violates"]):
            print(f"  {combo['id']}: skipped (refinement vectors do not validate under the documented layout)")
            continue
        cons = [Constraint.from_dict(d) for d in combo["constraints"]]
        best = None
        for i, r in enumerate(combo["refinements"]):
            sc = score(ds, combo["q1_sql"], r["sql"], cons, trials, seed)
            row = {"combo": combo["id"], "refinement": i, "q1": combo["q1_sql"], "q2": r["sql"], **sc}
            rows.append(row)
            if best is None or sc["score"] > best["score"]:
                best = {**row, "score": sc["score"]}
        print(f"  {combo['id']}: chose refinement {best['refinement']} of {len(combo['refinements'])} "
              f"(score {best['score']:.3f}, hidden drift {best['hidden_drift']:.2f} on {best['hidden_drift_attr']})")
        chosen.append({**combo, "q2_sql": best["q2"], "choice": best})
    od = out_dir("erica_selection", base)
    write_csv(pd.DataFrame(rows), od / "candidates.csv")
    write_json([{k: v for k, v in c.items() if k != "refinements"} for c in chosen], od / "chosen.json")
    path = CONFIG_DIR / "pairs.yaml"
    text = path.read_text()
    if MARK in text:
        text = text[:text.index(MARK)].rstrip() + "\n"
    path.write_text(text + _yaml_block(chosen))
    return {"chosen": chosen}
