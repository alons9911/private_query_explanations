"""Case studies for the pairs chosen by the pair search (R1-R6, C1-C4).

For every pair:
  * the E1 report (one eps = 1, k = 5 release, view stage, exact diagnostics);
  * what the analyst sees without the framework: sizes, constraint shares and
    the aggregate AVG(y) over both outputs;
  * the motivation metrics of :mod:`pqde.search` (hidden drift, drift inside the
    constrained group, the part of the aggregate change the constraint does not
    explain, and for CQA the drop and its unevenness);
  * stability: how often each (view, attribute) is released over 40 private runs;
  * quality: ApproxRatio against B1-B3 over the eps grid of E2.

Writes ``results/case_studies/<pair>/`` and ``results/case_studies/CASE_STUDIES_DATA.md``.
"""

from __future__ import annotations

from collections import Counter

import numpy as np
import pandas as pd
import yaml

from ..algorithm import explain
from ..data import CONFIG_DIR
from ..pairs import CASE_STUDY_PAIRS, resolve_pair
from ..search import hidden_attributes, max_tvd, pinned_attributes, score_refinement
from . import e1_case_studies
from .accuracy import accuracy_rows, summarise
from .common import (default_cache, make_params, out_dir, spawn_rngs, stable_key, to_markdown, write_csv,
                     write_json, write_raw)


def _proxies(dataset: str) -> dict:
    with open(CONFIG_DIR / "pair_search.yaml") as f:
        space = yaml.safe_load(f)
    return space.get("refinement", {}).get(dataset, {}).get("proxies", {})


def motivation_metrics(pid: str) -> dict:
    pair = resolve_pair(pid)
    ds = pair.dataset
    agg = pair.info.get("aggregate")
    if pair.kind == "refinement":
        c = pair.constraints[0]
        proxies = _proxies("tax" if ds.name.startswith("tax") else ds.name)
        m = score_refinement(ds, pair.q1_sql, pair.q2_sql, c, agg, proxies)
        m["hidden"] = hidden_attributes(ds, [pair.q1_sql, pair.q2_sql], c, proxies)
        return m
    q1, q2 = pair.q1, pair.q2
    hidden = [a for a in ds.explain_attrs if a not in pinned_attributes(pair.q1_sql)]
    dropped = q1 & ~q2
    unev, unev_attr = max_tvd(ds, hidden, dropped, q1)
    drift, drift_attr = max_tvd(ds, hidden, q1, q2)
    out = {"drop": float(dropped.sum() / q1.sum()), "unevenness": unev, "unevenness_attr": unev_attr,
           "hidden_drift": drift, "hidden_drift_attr": drift_attr, "hidden": hidden}
    # which values of the most uneven attribute the repair removes
    if unev_attr:
        codes, dom = ds.codes[unev_attr], ds.domains[unev_attr]
        n1 = np.bincount(codes[q1], minlength=len(dom))
        n2 = np.bincount(codes[q2], minlength=len(dom))
        lost = [(dom[i], int(n1[i]), int(n2[i])) for i in np.argsort(-(n1 - n2)) if n1[i] > 0][:6]
        out["largest_losses"] = [{"value": v, "|Q|": a, "|Q_Sigma|": b, "kept": round(b / a, 3)} for v, a, b in lost]
    return out


def stability(pid: str, cfg: dict, trials: int) -> dict:
    cache = default_cache(pid, cfg["defaults"])
    params = make_params(cfg["defaults"], cache.n_views, len(cache.explain_attrs))
    pairs_c, attrs_c = Counter(), Counter()
    for rng in spawn_rngs(int(cfg["defaults"]["seed"]), trials, stable_key(pid), 7):
        res = explain(cache, params, rng)
        for e in res.explanations:
            pairs_c[(e.view_label, e.attr)] += 1
            attrs_c[e.attr] += 1
    return {
        "trials": trials,
        "top_explanations": [{"view": v, "attr": a, "share_of_runs": round(n / trials, 3)}
                             for (v, a), n in pairs_c.most_common(10)],
        "attribute_share_of_runs": {a: round(n / trials, 3) for a, n in attrs_c.most_common()},
    }


def _key_bins(e: dict, sd: float, n: int = 4) -> list[dict]:
    nd = np.asarray(e["noisy_h1"]) - np.asarray(e["noisy_h2"])
    order = np.argsort(-np.abs(nd))[:n]
    return [{"bin": e["bins"][i], "noisy_Q1": round(e["noisy_h1"][i]), "noisy_Q2": round(e["noisy_h2"][i]),
             "exact_Q1": e["exact_h1"][i], "exact_Q2": e["exact_h2"][i], "clears_2sd": bool(abs(nd[i]) >= 2 * sd)}
            for i in order]


def run(cfg: dict, pairs: list[str] | None = None, base=None, quick: bool = False, trials: int | None = None) -> dict:
    pairs = pairs or CASE_STUDY_PAIRS
    trials = trials or (5 if quick else int(cfg["defaults"]["trials"]))
    od = out_dir("case_studies", base)
    lines = ["# Case-study pairs — data", "",
             "Generated by `pqde run cases`. Exact (`exact_*`) numbers are non-private diagnostics.", ""]
    acc_rows, overview = [], []
    for pid in pairs:
        print(f"  case study {pid}")
        rep = e1_case_studies.run_pair(pid, cfg, base, subdir="case_studies")
        pair = resolve_pair(pid)
        mm = motivation_metrics(pid)
        st = stability(pid, cfg, trials)
        rows, _ = accuracy_rows(pid, cfg, "epsilon", [0.5, 1.0, 2.0, 5.0], trials)
        summ = summarise(pd.DataFrame(rows)).rename(columns={"value": "epsilon"})
        acc_rows.append(summ)
        sd = rep["parameters"]["sigma_of_released_difference"]
        data = {"pair": rep["pair"], "motivation": mm, "stability": st,
                "accuracy": summ.to_dict(orient="records"), "explanations_key_bins":
                [{"view": e["view"], "attr": e["attr"], "bins": _key_bins(e, sd)} for e in rep["explanations"]]}
        write_json(data, od / pid / "case_study.json")
        p = rep["pair"]
        r1 = summ[np.isclose(summ.epsilon, 1.0)].iloc[0]
        ov = {"pair": pid, "dataset": p["dataset"], "kind": p["kind"], "role": pair.info.get("role", ""),
              "|Q1|": p["|Q1|"], "|Q2|": p["|Q2|"],
              "AVG_Q1": pair.info.get("AVG_Q1"), "AVG_Q2": pair.info.get("AVG_Q2"),
              "hidden_drift": mm.get("hidden_drift"), "drift_attr": mm.get("hidden_drift_attr"),
              "ratio_B2_eps1": r1.ratio_B2_mean, "top_attr_share": max(st["attribute_share_of_runs"].values())}
        if pair.kind == "refinement":
            c = pair.constraints[0]
            ov["constraint"] = f"{c.describe()}: {c.share(pair.dataset.raw, pair.q1):.1%} -> {c.share(pair.dataset.raw, pair.q2):.1%}"
            ov["agg_unexplained"] = mm.get("agg_unexplained")
        else:
            ov["constraint"] = f"Q_Sigma drops {mm['drop']:.1%}"
        overview.append(ov)
        # ---- data section
        lines += [f"## {pid} ({p['dataset']}, {p['kind']}, {pair.info.get('role', '')})", "",
                  f"* Q1: `{p['Q1']}` — |Q1| = {p['|Q1|']:,}", f"* Q2: `{p['Q2']}` — |Q2| = {p['|Q2|']:,}",
                  f"* {ov['constraint']}"]
        if pair.info.get("aggregate"):
            lines.append(f"* AVG({pair.info['aggregate']}): {pair.info['AVG_Q1']:.3f} → {pair.info['AVG_Q2']:.3f}")
        if pair.kind == "refinement":
            lines.append(f"* hidden drift {mm['hidden_drift']:.2f} on `{mm['hidden_drift_attr']}`; inside the "
                         f"constrained group {mm['group_drift']:.2f} on `{mm['group_drift_attr']}`; "
                         f"aggregate change not explained by the constraint: {mm.get('agg_unexplained', float('nan')):+.3f}")
        else:
            lines.append(f"* removed tuples most uneven over `{mm['unevenness_attr']}` (TVD {mm['unevenness']:.2f}); "
                         "largest losses: " + ", ".join(f"{x['value']} kept {x['kept']:.0%}" for x in mm.get("largest_losses", [])[:4]))
        lines.append(f"* ApproxRatio vs B2 at ε = 0.5 / 1 / 2 / 5: " + " / ".join(
            f"{v:.2f}" for v in summ.sort_values("epsilon").ratio_B2_mean))
        lines += ["", "Released explanations (ε = 1, one run; noisy vs exact on the bins with the largest released difference):", ""]
        for e in data["explanations_key_bins"]:
            kb = "; ".join(f"{b['bin']}: {b['noisy_Q1']}/{b['noisy_Q2']} (exact {b['exact_Q1']}/{b['exact_Q2']})"
                           + ("" if b["clears_2sd"] else " ~noise") for b in e["bins"])
            lines.append(f"* `{e['view']}` × **{e['attr']}** — {kb}")
        lines += ["", f"Stability over {trials} runs: " + ", ".join(
            f"`{x['view']}`×{x['attr']} {x['share_of_runs']:.0%}" for x in st["top_explanations"][:6]),
                  "", f"![{pid}]({pid}/explanations.png)", ""]
    ovdf = pd.DataFrame(overview)
    write_csv(ovdf, od / "overview.csv")
    acc = pd.concat(acc_rows, ignore_index=True)
    write_csv(acc, od / "accuracy.csv")
    head = ["## Overview", "", to_markdown(ovdf, floatfmt="{:.3f}"), ""]
    (od / "CASE_STUDIES_DATA.md").write_text("\n".join(lines[:4] + head + lines[4:]) + "\n")
    return {"overview": ovdf, "accuracy": acc}
